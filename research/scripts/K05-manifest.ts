// K05: writes the per-person Wikipedia entries at the end of research/manifests/K05.yaml, below MARK.
// Hand-written entries above MARK are kept as they are.
//   node research/scripts/K05-manifest.ts
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parse } from 'yaml'
import { PEOPLE } from './K05-ids.ts'

const ROOT = fileURLToPath(new URL('../..', import.meta.url))
const MARK = '  # --- generated by research/scripts/K05-manifest.ts: Wikipedia (basic career facts only) ---'
// people whose Wikidata item has no zhwiki sitelink, title found by hand
const EXTRA: Record<string, string> = {
  'song-dan': '宋丹_(中将)',
  'yan-zhichan': '严植婵',
  'yang-wei': '杨伟_(1963年5月)',
  'wang-hong': '王宏_(1963年)',
}

const titles = JSON.parse(readFileSync(join(ROOT, '.probe', 'K05-wiki-titles.json'), 'utf8')) as Record<string, string>
const file = join(ROOT, 'research', 'manifests', 'K05.yaml')
const head = readFileSync(file, 'utf8').split(MARK)[0].trimEnd()

// pages another batch already registered: cite theirs (person id -> source id), written to .probe/K05-reuse.json
const norm = (u: string) => decodeURIComponent(u).replace(/zh\.wikipedia\.org\/(zh-hans|zh-cn|zh|wiki|zh-hant)\//, 'W/').replace(/ /g, '_')
const others = new Map<string, string>()
for (const f of readdirSync(join(ROOT, 'research', 'manifests')).filter((f) => f.endsWith('.yaml') && f !== 'K05.yaml')) {
  try {
    for (const e of (parse(readFileSync(join(ROOT, 'research', 'manifests', f), 'utf8')) as { web?: { id: string; url: string }[] })?.web ?? []) others.set(norm(e.url), e.id)
  } catch {
    continue
  }
}
const reuse: Record<string, string> = {}

const lines = [head, MARK]
for (const [raw, id, q] of PEOPLE) {
  const title = (q && titles[q]) || EXTRA[id]
  if (!title) continue
  const other = others.get(norm(`https://zh.wikipedia.org/zh-hans/${title}`))
  if (other) {
    reuse[id] = other
    continue
  }
  const name = raw.replace(/（.*?）/g, '')
  lines.push(`  - { id: k05-wiki-${id}, title: ${name}（维基百科）, publisher: 维基百科, voice: wiki, url: "https://zh.wikipedia.org/zh-hans/${title.replace(/ /g, '_')}", excerpt: true, keep: [ ${name}, 年 ] }`)
}
writeFileSync(file, lines.join('\n') + '\n')
writeFileSync(join(ROOT, '.probe', 'K05-reuse.json'), JSON.stringify(reuse, null, 1))
console.log(`${lines.length - 2} wiki entries, ${Object.keys(reuse).length} reused`)
