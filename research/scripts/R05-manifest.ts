// R05: write research/manifests/R05.yaml from R05-sources.ts, adding start/end from .probe/R05-markers.json
// and reporting URLs another manifest already registers (.probe/R05-dupes.txt: our id, their id).
// Usage: node research/scripts/R05-manifest.ts [--drop=id,id]
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { parse, stringify } from 'yaml'
import { SOURCES } from './R05-sources.ts'

const root = join(import.meta.dirname, '..', '..')
const drop = new Set((process.argv.find((a) => a.startsWith('--drop='))?.slice(7) ?? '').split(',').filter(Boolean))
const norm = (u: string) =>
  u
    .replace(/^https?:\/\/web\.archive\.org\/web\/\w+\//, '')
    .replace(/^https?:\/\/(www\.|m\.)?/, '')
    .replace(/\/+/g, '/')
    .replace(/\/$/, '')

const others = new Map<string, string>()
for (const f of readdirSync(join(root, 'research/manifests')).filter((f) => f.endsWith('.yaml') && f !== 'R05.yaml')) {
  try {
    const m = parse(readFileSync(join(root, 'research/manifests', f), 'utf8')) as { web?: { id: string; url: string }[] } | null
    for (const e of m?.web ?? []) others.set(norm(e.url), `${e.id}\t${f}`)
  } catch {
    // a manifest another batch is still writing
  }
}

const markers: Record<string, { start?: string; end?: string; error?: string }> = existsSync(join(root, '.probe/R05-markers.json'))
  ? JSON.parse(readFileSync(join(root, '.probe/R05-markers.json'), 'utf8'))
  : {}

const dupes: string[] = []
const web = SOURCES.filter((s) => !drop.has(s.id)).flatMap((s) => {
  const hit = others.get(norm(s.url))
  if (hit) {
    dupes.push(`${s.id}\t${hit}`)
    return []
  }
  const e: Record<string, unknown> = { id: s.id, title: s.title, publisher: s.publisher, date: s.date, voice: s.voice ?? 'official', url: s.url }
  if (s.full === false) Object.assign(e, { excerpt: true, keep: s.keep })
  else {
    const m = markers[s.id]
    if (m?.start) e.start = m.start
    if (m?.end) e.end = m.end
  }
  return [e]
})

const head = [
  '# R05 (round 6): centrally managed cadres (not the army) first announced as under CCDI investigation in 2021–2023.',
  '# www.ccdi.gov.cn answers scripted requests with a captcha page, so CCDI notices are Wayback raw snapshots (id_)',
  '# taken before the captcha; court, procuratorate and Xinhua pages are fetched directly. Generated by',
  '# research/scripts/R05-manifest.ts from research/scripts/R05-sources.ts.',
  '',
].join('\n')
writeFileSync(join(root, 'research/manifests/R05.yaml'), head + stringify({ web }, { lineWidth: 0 }), 'utf8')
writeFileSync(join(root, '.probe/R05-dupes.txt'), dupes.join('\n'), 'utf8')
console.log(`${web.length} sources, ${dupes.length} dupes`)
