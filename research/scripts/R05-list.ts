if (import.meta.url === `file:///${process.argv[1].replace(/\\/g, '/')}`) {
  type P = { id: string; name: string; fall?: { date: string }[]; status?: string; positions?: { title: string }[] }
  const people: (P & { file: string })[] = []
  const dir = join(ROOT, 'content', 'people')
  for (const f of readdirSync(dir).filter((f) => f.endsWith('.yaml') && !f.startsWith('R0'))) {
    try {
      for (const p of (parse(readFileSync(join(dir, f), 'utf8')) as P[]) ?? []) people.push({ ...p, file: f })
    } catch (e) {
      console.error('skip', f, (e as Error).message.split('\n')[0])
    }
  }
  const rosters: { id: string; name: string; batch: string }[] = []
  for (const f of ['research/roster.yaml', ...readdirSync(join(ROOT, 'research', 'roster')).map((f) => `research/roster/${f}`)]) {
    if (f.includes('R05')) continue
    try {
      rosters.push(...((parse(readFileSync(join(ROOT, f), 'utf8')) as typeof rosters) ?? []))
    } catch {}
  }
  const falls = new Set<string>()
  for (const f of readdirSync(join(ROOT, 'content', 'falls')).filter((f) => !f.startsWith('R05')))
    try {
      for (const k of Object.keys(parse(readFileSync(join(ROOT, 'content', 'falls', f), 'utf8')) ?? {})) falls.add(k)
    } catch {}
  const prev = new Map<string, { id?: string; done?: boolean }>()
  const listPath = join(ROOT, 'research', 'falls-list', 'R05.yaml')
  if (existsSync(listPath)) for (const r of (parse(readFileSync(listPath, 'utf8')) as { name: string; id?: string; done?: boolean }[]) ?? []) prev.set(r.name, r)
  const report: string[] = []
  const yaml: string[] = [
    '# R05: centrally managed cadres (not army) whose first CCDI notice of investigation fell in 2021-01 .. 2023-12.',
    '# 25 (2021) + 34 (2022: the 32 of the probe column plus 李泽峰 and 李佳, first announced with their punishment) + 45 (2023).',
    '# 吴燕生 and 刘石泉 (2023-12-27, removed from the CPPCC without a CCDI notice) are left out.',
    '# Sources: CCDI column "审查调查 · 中管干部 · 执纪审查" (Wayback snapshots), zhwiki fall lists. Generated by research/scripts/R05-list.ts.',
  ]
  for (const [name, date, post] of LIST) {
    const hits = people.filter((p) => p.name === name)
    const ros = rosters.filter((r) => r.name === name)
    report.push(
      `${date} ${name}\t${post}\n    people: ${hits.map((h) => `${h.id}(${h.file},${h.status},fall:${(h.fall ?? []).map((s) => s.date).join('/')})`).join(' ; ') || '-'}\n    roster: ${ros.map((r) => `${r.id}/${r.batch}`).join(' ; ') || '-'}${hits.some((h) => falls.has(h.id)) ? '\n    HAS CASE RECORD' : ''}`,
    )
    const p = prev.get(name)
    const id = p?.id ?? (hits.length === 1 ? hits[0].id : '')
    yaml.push(`- { name: ${name}, date: ${date}, post: "${post}", id: ${id || "''"}, done: ${p?.done ?? (name === '宋亮')} }`)
  }
  writeFileSync(join(ROOT, '.probe', 'R05-list.txt'), report.join('\n') + '\n')
  writeFileSync(listPath, yaml.join('\n') + '\n')
  console.log(LIST.length, 'names')
}
