// Registers each K06 person's zh.wikipedia article in research/manifests/K06.yaml (between the generated markers),
// reusing an id another batch already registered for the same article.
//   node research/scripts/K06-wiki.ts   -> rewrites the generated block, .probe/K06-wiki.json (person key -> source id)
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parse } from 'yaml'
import { IDS, PICKS } from './K06-ids.ts'

const ROOT = fileURLToPath(new URL('../..', import.meta.url))
const UA = 'new-era-research/0.1 (https://github.com/AndyUneducated/new-era)'
const read = (...p: string[]) => readFileSync(join(ROOT, ...p), 'utf8')
const auto = JSON.parse(read('.probe', 'K06-picks.json')) as Record<string, { qid?: string; wiki?: string }>
const qid = (k: string) => PICKS[k] ?? auto[k]?.qid
// articles Wikidata does not link
const TITLES: Record<string, string> = { 刘敬桢: '刘敬桢', 王庭凯: '王庭凯' }

const need = Object.keys(IDS).filter((k) => qid(k) && !auto[k]?.wiki)
const titles = new Map<string, string>()
for (let i = 0; i < need.length; i += 50) {
  const u = new URL('https://www.wikidata.org/w/api.php')
  const ids = need.slice(i, i + 50).map(qid)
  for (const [k, v] of Object.entries({ format: 'json', action: 'wbgetentities', ids: ids.join('|'), props: 'sitelinks', sitefilter: 'zhwiki' })) u.searchParams.set(k, v)
  const r = await (await fetch(u, { headers: { 'User-Agent': UA } })).json()
  for (const [q, e] of Object.entries(r.entities as Record<string, { sitelinks?: { zhwiki?: { title: string } } }>)) if (e.sitelinks?.zhwiki) titles.set(q, e.sitelinks.zhwiki.title)
}

const norm = (u: string) => decodeURIComponent(u).replace(/^https?:\/\/zh\.(m\.)?wikipedia\.org\/(zh-hans|zh-cn|zh|wiki)\//, '').replace(/ /g, '_')
const existing = new Map<string, string>()
for (const f of readdirSync(join(ROOT, 'research', 'manifests')).filter((f) => f.endsWith('.yaml') && f !== 'K06.yaml'))
  try {
    for (const e of ((parse(read('research', 'manifests', f)) as { web?: { id: string; url: string }[] })?.web ?? [])) if (/wikipedia\.org/.test(e.url)) existing.set(norm(e.url), e.id)
  } catch {}

const map: Record<string, string> = {}
const lines: string[] = []
const missing: string[] = []
for (const [k, id] of Object.entries(IDS)) {
  const q = qid(k)
  const title = (auto[k]?.wiki ?? (q ? titles.get(q) : undefined) ?? TITLES[k])?.replace(/ /g, '_')
  if (!title) {
    missing.push(k)
    continue
  }
  const name = k.replace(/（[^）]*）/g, '')
  const reuse = existing.get(title)
  if (reuse) {
    map[k] = reuse
    continue
  }
  const sid = `k06-wiki-${id}`
  map[k] = sid
  lines.push(`  - { id: ${sid}, title: ${name}（维基百科）, publisher: 维基百科, voice: wiki, url: "https://zh.wikipedia.org/zh-hans/${title}", excerpt: true, keep: [ ${name}, 年 ] }`)
}
const BEGIN = '  # --- per-person articles, generated by research/scripts/K06-wiki.ts ---'
const END = '  # --- end of generated block ---'
const man = read('research', 'manifests', 'K06.yaml')
const block = [BEGIN, ...lines, END].join('\n')
const next = man.includes(BEGIN) ? man.replace(new RegExp(`${BEGIN.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`), block) : man.trimEnd() + '\n' + block + '\n'
writeFileSync(join(ROOT, 'research', 'manifests', 'K06.yaml'), next)
writeFileSync(join(ROOT, '.probe', 'K06-wiki.json'), JSON.stringify(map, null, 1))
console.log(`${lines.length} new, ${Object.keys(map).length - lines.length} reused, no article: ${missing.join(' ')}`)
