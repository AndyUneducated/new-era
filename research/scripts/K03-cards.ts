// Builds content/people/K03.yaml from the hand-written blocks in K03-data.ts plus the Wikidata facts,
// and the zhwiki biography sources (k03-wiki-<id>) at the end of research/manifests/K03.yaml; a page another
// batch already has is cited under that batch's id instead.
//   node research/scripts/K03-cards.ts   -> content/people/K03.yaml, research/manifests/K03.yaml (generated part)
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parse } from 'yaml'
import { CARDS } from './K03-data.ts'

const ROOT = fileURLToPath(new URL('../..', import.meta.url))
const read = (p: string) => readFileSync(join(ROOT, p), 'utf8')

const roster = parse(read('research/roster/K03.yaml')) as { id: string; name: string }[]
const idOf = new Map(roster.map((r) => [r.name, r.id]))
type Fact = { q: string; list: 'cc' | 'cca'; gender: 'm' | 'f'; ethnicity?: string; born?: string; died?: string }
const facts = JSON.parse(read('.probe/K03-facts.json')) as Record<string, Fact>

// a later full-member seat makes the role cc
const bare = (s: string) => s.replace(/（.*?）/g, '')
const terms = parse(read('content/congresses/K01.yaml')) as { n: number; cc?: string[] }[]
const everCc = new Set(terms.filter((t) => t.n >= 16).flatMap((t) => (t.cc ?? []).map(bare)))

const titles = new Map<string, string>()
for (const m of read('.probe/K03-screen.txt').matchAll(/^(?:!!| {2}) (\S+) (Q\d+) (.+) \d+$/gm)) titles.set(m[1], m[3])
const wikiUrl = (title: string) => `https://zh.wikipedia.org/zh-hans/${title.replace(/ /g, '_')}`

// a zhwiki page another batch already registered (with text) is cited under that batch's id
const known = new Map<string, string>()
for (const file of readdirSync(join(ROOT, 'research/manifests'))) {
  if (!file.endsWith('.yaml') || file === 'K03.yaml') continue
  const web = (parse(read(`research/manifests/${file}`)) as { web?: { id: string; url?: string }[] } | null)?.web ?? []
  for (const e of web) if (e.url && existsSync(join(ROOT, 'sources/text', `${e.id}.txt`))) known.set(e.url, e.id)
}

type Card = { name: string; extra: string[]; born?: string; birthplace?: string; h?: string; b?: string; p: string[][]; s?: string; n?: string; d?: string; f: string[][] }
const cards: Card[] = []
for (const block of CARDS.split(/^@/m).slice(1)) {
  const [head, ...lines] = block.trim().split('\n')
  const [name, extra, born, birthplace] = head.split('|').map((s) => s.trim())
  const c: Card = { name, extra: extra ? extra.split(/\s+/) : [], born: born || undefined, birthplace: birthplace || undefined, p: [], f: [] }
  for (const line of lines) {
    const k = line.slice(0, 1)
    const v = line.slice(2).trim()
    if (k === 'p') c.p.push(v.split('|').map((s) => s.trim()))
    else if (k === 'f') c.f.push(v.split('|').map((s) => s.trim()))
    else if (k === 'h' || k === 'b' || k === 's' || k === 'n' || k === 'd') c[k] = v
  }
  cards.push(c)
}

const problems: string[] = []
const q = (s: string) => (/^[^\s'"`@&*!|>%#{}[\],:?-][^#{}[\],:]*$/.test(s) && !/^\d[\d-]*$/.test(s) && !/: |\s#/.test(s) ? s : JSON.stringify(s))
const fallen = (c: Card) => c.f.length > 0
const out: string[] = ['# K03 (round 4): dossier cards for people first named to the 16th CC (2002) or as alternates.', '# Generated by research/scripts/K03-cards.ts from research/scripts/K03-data.ts; edit those, not this file.', '']
const wiki: string[] = []
const seen = new Set<string>()
for (const c of [...cards.filter(fallen), ...cards.filter((c) => !fallen(c))]) {
  const id = idOf.get(c.name)
  const f = facts[c.name]
  if (!id || !f) {
    problems.push(`not on roster: ${c.name}`)
    continue
  }
  if (seen.has(id)) problems.push(`twice: ${c.name}`)
  seen.add(id)
  const title = titles.get(c.name)
  const other = title ? known.get(wikiUrl(title)) : undefined
  const wid = other ?? `k03-wiki-${id}`
  const list = f.list === 'cc' ? 'k02-xinhua-2002-11-14-16-cc' : 'k02-xinhua-2002-11-14-16-cca'
  const roles = [...(everCc.has(c.name) ? ['cc'] : ['acc']), ...c.extra]
  const died = c.d ?? f.died
  const status = c.s ?? (died ? 'dead' : 'retired')
  const born = c.born ?? f.born
  const L: string[] = [`- id: ${id}`, `  name: ${c.name}`, `  gender: ${f.gender}`]
  if (f.ethnicity) L.push(`  ethnicity: ${f.ethnicity}`)
  if (born) L.push(`  born: ${born}`)
  if (died) L.push(`  died: ${died}`)
  if (c.birthplace) L.push(`  birthplace: ${q(c.birthplace)}`)
  L.push(`  roles: [${roles.join(', ')}]`, `  status: ${status}`)
  if (c.n) L.push(`  statusNote: ${q(c.n)}`)
  if (c.f.length) {
    L.push('  fall:')
    for (const [d, text, cite] of c.f) L.push(`    - { date: ${d}, text: ${q(text)}, cite: ${cite} }`)
  }
  if (!c.h || !c.b) problems.push(`no headline/bio: ${c.name}`)
  L.push('  tier: 2', `  headline: ${q(c.h ?? '')}`, `  ids: { wikidata: ${f.q} }`, '  bio: >-', `    ${c.b ?? ''}`)
  if (c.p.length) {
    L.push('  positions:')
    for (const [t, sys, place, from, to] of c.p) {
      const parts = [`title: ${q(t)}`, `sys: ${sys}`]
      if (place) parts.push(`place: ${place}`)
      if (from) parts.push(`from: ${from}`)
      if (to) parts.push(`to: ${to}`)
      if (title) parts.push(`cite: ${wid}`)
      L.push(`    - { ${parts.join(', ')} }`)
    }
  }
  if (status === 'dead' && !died) problems.push(`dead without date: ${c.name}`)
  if (died && status !== 'dead') problems.push(`died but status ${status}: ${c.name}`)
  const cites = [...new Set([`wd-${f.q}`, ...(title ? [wid] : []), list, ...c.f.map((x) => x[2])])]
  L.push(`  cites: [${cites.join(', ')}]`, '')
  out.push(...L)

  if (title && !other) {
    const extract = existsSync(join(ROOT, '.probe/K03-wiki', `${c.name}-${f.q}.txt`)) ? read(`.probe/K03-wiki/${c.name}-${f.q}.txt`) : ''
    const keep = [`${c.name}（`, ...new Set(c.p.flatMap(([, , , from]) => (from ? [`${from.slice(0, 4)}年`] : [])))].filter((k) => extract.includes(k.replace(/（$/, '')))
    const url = wikiUrl(title)
    wiki.push(`  - { id: ${wid}, title: ${c.name}（维基百科）, publisher: 维基百科, voice: wiki, url: ${q(url)}, excerpt: true, keep: [ ${keep.map(q).join(', ')} ] }`)
  } else if (!title) problems.push(`no zhwiki: ${c.name}`)
}

writeFileSync(join(ROOT, 'content/people/K03.yaml'), out.join('\n'))
const MARK = '  # --- zhwiki biographies, generated by research/scripts/K03-cards.ts ---'
const manifest = read('research/manifests/K03.yaml')
const head = manifest.includes(MARK) ? manifest.slice(0, manifest.indexOf(MARK)) : manifest.replace(/\s*$/, '\n')
writeFileSync(join(ROOT, 'research/manifests/K03.yaml'), `${head}${MARK}\n${wiki.join('\n')}\n`)
writeFileSync(join(ROOT, '.probe/K03-cards.txt'), `${cards.length} cards\n${problems.join('\n')}\n`)
console.log(`${cards.length} cards, ${problems.length} problems -> .probe/K03-cards.txt`)
